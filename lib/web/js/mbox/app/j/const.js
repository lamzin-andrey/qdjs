var IDABORT    = 3; // Нажата кнопка «Прервать»
var IDRETRY    = 4; // Нажата кнопка «Повтор»
var IDIGNORE   = 5; // Нажата кнопка «Пропустить»
var IDYES      = 6; // Нажата кнопка «Да»
var IDNO       = 7; // Нажата кнопка «Нет»
var IDTRYAGAIN = 10; // Нажата кнопка «Повторить» (CANCELTRYCONTINUE)
var IDCONTINUE = 11; // Нажата кнопка «Продолжить» (CANCELTRYCONTINUE)
var IDTIMEOUT  = 32000; // Тайм-аут (если использовался MB_TIMEDOUT)



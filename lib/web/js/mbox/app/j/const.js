/**
 * Константы для функции MessageBox (WinAPI).
 * Значения взяты из официальной документации Microsoft (winuser.h).
 *
 * В JavaScript нет суффикса "L" (long), поэтому используется обычный Number.
 * Значения записаны в шестнадцатеричном виде для наглядности.
 *
 * Комбинирование флагов выполняется через побитовое ИЛИ (|):
 *   var type = MB_YESNO | MB_ICONQUESTION | MB_DEFBUTTON2;
 */


var MB_OK                = 0x00000000; // Только кнопка «ОК» (по умолчанию)
var MB_OKCANCEL          = 0x00000001; // Кнопки «ОК» и «Отмена»
var MB_ABORTRETRYIGNORE  = 0x00000002; // Кнопки «Прервать», «Повтор» и «Пропустить»
var MB_YESNOCANCEL       = 0x00000003; // Кнопки «Да», «Нет» и «Отмена»
var MB_YESNO             = 0x00000004; // Кнопки «Да» и «Нет»
var MB_RETRYCANCEL       = 0x00000005; // Кнопки «Повтор» и «Отмена»
var MB_CANCELTRYCONTINUE = 0x00000006; // Кнопки «Отмена», «Повтор» и «Продолжить»
var MB_HELP              = 0x00004000; // Добавляет кнопку «Справка»


// ─────────────────────────────────────────────────────────────────────────────
// 🖼️ ИКОНКИ (выберите ОДНУ константу из этой группы)
// ─────────────────────────────────────────────────────────────────────────────

var MB_ICONHAND        = 0x00000010; // Иконка ошибки (красный знак «стоп»)
var MB_ICONSTOP        = 0x00000010; // Синоним MB_ICONHAND
var MB_ICONERROR       = 0x00000010; // Синоним MB_ICONHAND
var MB_ICONQUESTION    = 0x00000020; // Иконка вопроса (не рекомендуется)
var MB_ICONEXCLAMATION = 0x00000030; // Иконка предупреждения (жёлтый треугольник)
var MB_ICONWARNING     = 0x00000030; // Синоним MB_ICONEXCLAMATION
var MB_ICONASTERISK    = 0x00000040; // Информационная иконка (синий круг с «i»)
var MB_ICONINFORMATION = 0x00000040; // Синоним MB_ICONASTERISK


// ─────────────────────────────────────────────────────────────────────────────
//  КНОПКА ПО УМОЛЧАНИЮ (выберите ОДНУ константу из этой группы)
// ─────────────────────────────────────────────────────────────────────────────

var MB_DEFBUTTON1 = 0x00000000; // Первая кнопка — по умолчанию
var MB_DEFBUTTON2 = 0x00000100; // Вторая кнопка — по умолчанию
var MB_DEFBUTTON3 = 0x00000200; // Третья кнопка — по умолчанию
var MB_DEFBUTTON4 = 0x00000300; // Четвёртая кнопка — по умолчанию


// ─────────────────────────────────────────────────────────────────────────────
// ️ МОДАЛЬНОСТЬ И ПОВЕДЕНИЕ ОКНА
// ─────────────────────────────────────────────────────────────────────────────

var MB_APPLMODAL             = 0x00000000; // Блокирует только родительское окно (по умолчанию)
var MB_SYSTEMMODAL           = 0x00001000; // Окно «поверх всех», привлекает внимание
var MB_TASKMODAL             = 0x00002000; // Блокирует все окна потока, если hWnd = NULL
var MB_SETFOREGROUND         = 0x00010000; // Выводит окно на передний план
var MB_DEFAULT_DESKTOP_ONLY  = 0x00020000; // Показывать только на рабочем столе по умолчанию
var MB_TOPMOST               = 0x00040000; // Окно создаётся «поверх всех окон»
var MB_RIGHT                 = 0x00080000; // Выравнивание текста по правому краю
var MB_RTLREADING            = 0x00100000; // Текст справа налево (арабский/иврит)
var MB_SERVICE_NOTIFICATION  = 0x00200000; // Для служб: показ окна в активной сессии пользователя


// ─────────────────────────────────────────────────────────────────────────────
//  ВОЗВРАЩАЕМЫЕ ЗНАЧЕНИЯ (результат, который вернёт MessageBox)
// ─────────────────────────────────────────────────────────────────────────────

var IDOK       = 1; // Нажата кнопка «ОК»
